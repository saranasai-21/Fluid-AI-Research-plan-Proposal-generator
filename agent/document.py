"""
Fluid AI — Document Generator
Converts markdown content from the agent into a polished Microsoft Word (.docx) document.
Uses python-docx for document creation with professional formatting.
"""

from __future__ import annotations

import re
import logging
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.shared import Inches, Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_TABLE_ALIGNMENT

from config import (
    OUTPUT_DIR,
    DOCUMENT_FONT,
    DOCUMENT_TITLE_SIZE,
    DOCUMENT_HEADING_SIZE,
    DOCUMENT_BODY_SIZE,
)
from models.schemas import ExecutionPlan, StepResult, StepStatus, ReflectionResult

logger = logging.getLogger("fluid_ai.document")


class DocumentGenerator:
    """
    Generates professional Word documents from the agent's output.
    Handles markdown-to-docx conversion with proper formatting.
    """

    # Color scheme for the document
    PRIMARY_COLOR = RGBColor(0x1A, 0x56, 0xDB)     # Deep blue
    SECONDARY_COLOR = RGBColor(0x37, 0x41, 0x51)    # Dark gray
    ACCENT_COLOR = RGBColor(0x05, 0x96, 0x69)       # Teal green
    LIGHT_BG = RGBColor(0xF3, 0xF4, 0xF6)           # Light gray

    def __init__(self):
        self.doc = Document()
        self._setup_styles()

    def _setup_styles(self):
        """Configure default document styles."""
        style = self.doc.styles["Normal"]
        font = style.font
        font.name = DOCUMENT_FONT
        font.size = Pt(DOCUMENT_BODY_SIZE)
        font.color.rgb = self.SECONDARY_COLOR

        paragraph_format = style.paragraph_format
        paragraph_format.space_after = Pt(6)
        paragraph_format.line_spacing = 1.15

    def generate(
        self,
        plan: ExecutionPlan,
        step_results: list[StepResult],
        reflection: ReflectionResult | None,
        user_request: str,
    ) -> Path:
        """
        Generate a complete Word document from the agent's output.

        Args:
            plan: The execution plan.
            step_results: Results from all executed steps.
            reflection: Quality review results (may contain refined content).
            user_request: The original user request.

        Returns:
            Path to the generated .docx file.
        """
        logger.info(f"Generating document: {plan.document_title}")

        # Add title page
        self._add_title_page(plan, user_request)

        # Add table of contents placeholder
        self._add_table_of_contents()

        # Determine which content to use (refined if available)
        if reflection and reflection.refined_content:
            content = reflection.refined_content
        else:
            content = self._assemble_content(step_results)

        # Parse and add content
        self._add_content(content)

        # Add footer with metadata
        self._add_footer(plan)

        # Save the document
        filename = self._generate_filename(plan)
        filepath = OUTPUT_DIR / filename
        self.doc.save(str(filepath))
        logger.info(f"Document saved to: {filepath}")

        return filepath

    def _add_title_page(self, plan: ExecutionPlan, user_request: str):
        """Add a professional title page."""
        # Add spacing before title
        for _ in range(4):
            self.doc.add_paragraph("")

        # Document title
        title_para = self.doc.add_paragraph()
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        title_run = title_para.add_run(plan.document_title)
        title_run.font.size = Pt(DOCUMENT_TITLE_SIZE)
        title_run.font.color.rgb = self.PRIMARY_COLOR
        title_run.font.bold = True
        title_run.font.name = DOCUMENT_FONT

        # Subtitle line
        self.doc.add_paragraph("")
        line_para = self.doc.add_paragraph()
        line_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        line_run = line_para.add_run("━" * 40)
        line_run.font.color.rgb = self.ACCENT_COLOR
        line_run.font.size = Pt(12)

        # Document type
        type_para = self.doc.add_paragraph()
        type_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        type_run = type_para.add_run(
            plan.document_type.replace("_", " ").title()
        )
        type_run.font.size = Pt(14)
        type_run.font.color.rgb = self.SECONDARY_COLOR
        type_run.font.italic = True

        # Date
        self.doc.add_paragraph("")
        date_para = self.doc.add_paragraph()
        date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        date_run = date_para.add_run(
            f"Generated on {datetime.now().strftime('%B %d, %Y')}"
        )
        date_run.font.size = Pt(11)
        date_run.font.color.rgb = self.SECONDARY_COLOR

        # Generated by
        gen_para = self.doc.add_paragraph()
        gen_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        gen_run = gen_para.add_run("Generated by Fluid AI — Autonomous Agent")
        gen_run.font.size = Pt(10)
        gen_run.font.color.rgb = RGBColor(0x9C, 0xA3, 0xAF)
        gen_run.font.italic = True

        # Page break after title
        self.doc.add_page_break()

    def _add_table_of_contents(self):
        """Add a table of contents heading (Word requires manual update)."""
        toc_heading = self.doc.add_heading("Table of Contents", level=1)
        for run in toc_heading.runs:
            run.font.color.rgb = self.PRIMARY_COLOR

        toc_note = self.doc.add_paragraph()
        note_run = toc_note.add_run(
            "[Right-click and select 'Update Field' to generate table of contents in Word]"
        )
        note_run.font.size = Pt(9)
        note_run.font.color.rgb = RGBColor(0x9C, 0xA3, 0xAF)
        note_run.font.italic = True

        self.doc.add_paragraph("")
        self.doc.add_page_break()

    def _add_content(self, content: str):
        """Parse markdown content and add it to the document with formatting."""
        lines = content.split("\n")
        i = 0
        in_table = False
        table_rows = []

        while i < len(lines):
            line = lines[i].strip()

            # Skip empty lines
            if not line:
                i += 1
                continue

            # Skip horizontal rules
            if line in ("---", "***", "___"):
                i += 1
                continue

            # Detect table rows
            if "|" in line and not line.startswith("```"):
                # Check if this is a table separator line
                if re.match(r"^\|[\s\-:|]+\|$", line):
                    i += 1
                    continue

                if not in_table:
                    in_table = True
                    table_rows = []

                # Parse table row
                cells = [c.strip() for c in line.split("|")]
                cells = [c for c in cells if c]  # Remove empty strings
                table_rows.append(cells)
                i += 1

                # Check if next line is not a table row
                if i >= len(lines) or "|" not in lines[i]:
                    self._add_table(table_rows)
                    in_table = False
                    table_rows = []
                continue

            # Headings
            if line.startswith("#"):
                level = min(len(line.split(" ")[0]), 4)  # Count #'s, max level 4
                text = line.lstrip("#").strip()
                heading = self.doc.add_heading(text, level=level)
                for run in heading.runs:
                    run.font.color.rgb = self.PRIMARY_COLOR
                    run.font.name = DOCUMENT_FONT
                i += 1
                continue

            # Bullet points
            if line.startswith(("- ", "* ", "• ")):
                text = line[2:].strip()
                text = self._clean_markdown_inline(text)
                para = self.doc.add_paragraph(text, style="List Bullet")
                self._apply_inline_formatting(para, text)
                i += 1
                continue

            # Numbered lists
            numbered_match = re.match(r"^(\d+)\.\s+(.*)", line)
            if numbered_match:
                text = numbered_match.group(2).strip()
                text = self._clean_markdown_inline(text)
                para = self.doc.add_paragraph(text, style="List Number")
                self._apply_inline_formatting(para, text)
                i += 1
                continue

            # Regular paragraphs
            text = self._clean_markdown_inline(line)
            para = self.doc.add_paragraph()
            self._add_formatted_run(para, text)
            i += 1

    def _add_table(self, rows: list[list[str]]):
        """Add a formatted table to the document."""
        if not rows:
            return

        num_cols = max(len(row) for row in rows)
        table = self.doc.add_table(rows=len(rows), cols=num_cols)
        table.style = "Light Grid Accent 1"
        table.alignment = WD_TABLE_ALIGNMENT.CENTER

        for row_idx, row_data in enumerate(rows):
            for col_idx, cell_text in enumerate(row_data):
                if col_idx < num_cols:
                    cell = table.rows[row_idx].cells[col_idx]
                    cell.text = self._clean_markdown_inline(cell_text)

                    # Bold header row
                    if row_idx == 0:
                        for paragraph in cell.paragraphs:
                            for run in paragraph.runs:
                                run.font.bold = True
                                run.font.color.rgb = self.PRIMARY_COLOR

        self.doc.add_paragraph("")  # Spacing after table

    def _add_formatted_run(self, paragraph, text: str):
        """Add text with inline formatting (bold, italic) to a paragraph."""
        paragraph.clear()
        # Split by bold markers
        parts = re.split(r"(\*\*.*?\*\*)", text)
        for part in parts:
            if part.startswith("**") and part.endswith("**"):
                run = paragraph.add_run(part[2:-2])
                run.font.bold = True
                run.font.name = DOCUMENT_FONT
            else:
                # Check for italic
                italic_parts = re.split(r"(\*.*?\*)", part)
                for ipart in italic_parts:
                    if ipart.startswith("*") and ipart.endswith("*") and len(ipart) > 2:
                        run = paragraph.add_run(ipart[1:-1])
                        run.font.italic = True
                        run.font.name = DOCUMENT_FONT
                    else:
                        run = paragraph.add_run(ipart)
                        run.font.name = DOCUMENT_FONT

    def _apply_inline_formatting(self, paragraph, text: str):
        """Re-apply inline formatting for list items."""
        if "**" in text or "*" in text:
            self._add_formatted_run(paragraph, text)

    @staticmethod
    def _clean_markdown_inline(text: str) -> str:
        """Remove markdown formatting characters for plain text contexts."""
        # Remove bold/italic markers for plain text
        text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
        text = re.sub(r"\*(.*?)\*", r"\1", text)
        # Remove inline code backticks
        text = re.sub(r"`(.*?)`", r"\1", text)
        return text.strip()

    def _add_footer(self, plan: ExecutionPlan):
        """Add document metadata footer."""
        self.doc.add_paragraph("")
        self.doc.add_page_break()

        # Appendix
        appendix = self.doc.add_heading("Document Information", level=1)
        for run in appendix.runs:
            run.font.color.rgb = self.PRIMARY_COLOR

        info_items = [
            ("Document Type", plan.document_type.replace("_", " ").title()),
            ("Generated On", datetime.now().strftime("%B %d, %Y at %I:%M %p")),
            ("Generator", "Fluid AI — Autonomous Document Agent"),
            ("AI Model", "Llama 3.3 70B via Groq"),
            ("Planning Method", "Multi-step autonomous planning with reflection"),
        ]

        for label, value in info_items:
            para = self.doc.add_paragraph()
            label_run = para.add_run(f"{label}: ")
            label_run.font.bold = True
            label_run.font.color.rgb = self.SECONDARY_COLOR
            label_run.font.name = DOCUMENT_FONT
            value_run = para.add_run(value)
            value_run.font.name = DOCUMENT_FONT

        # Disclaimer
        self.doc.add_paragraph("")
        disclaimer = self.doc.add_paragraph()
        disc_run = disclaimer.add_run(
            "Disclaimer: This document was autonomously generated by an AI agent. "
            "While it contains plausible and structured content, all data, figures, "
            "and recommendations should be reviewed and validated by relevant stakeholders "
            "before any business decisions are made."
        )
        disc_run.font.size = Pt(9)
        disc_run.font.italic = True
        disc_run.font.color.rgb = RGBColor(0x9C, 0xA3, 0xAF)

    @staticmethod
    def _generate_filename(plan: ExecutionPlan) -> str:
        """Generate a unique filename for the document."""
        # Sanitize title for filename
        safe_title = re.sub(r"[^\w\s-]", "", plan.document_title)
        safe_title = re.sub(r"\s+", "_", safe_title.strip())
        safe_title = safe_title[:50]  # Limit length
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        return f"{safe_title}_{timestamp}.docx"

    @staticmethod
    def _assemble_content(step_results: list[StepResult]) -> str:
        """Assemble content from completed steps."""
        parts = []
        for result in step_results:
            if result.status == StepStatus.COMPLETED and result.content:
                parts.append(result.content)
        return "\n\n".join(parts)
