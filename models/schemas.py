"""
Fluid AI — Pydantic Schemas
Defines all request/response models for the API and internal agent communication.
"""

from __future__ import annotations

from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field


# ─── Enums ───────────────────────────────────────────────────────────────────

class StepType(str, Enum):
    """Types of steps the agent can plan."""
    ANALYZE = "analyze"
    RESEARCH = "research"
    GENERATE = "generate"
    STRUCTURE = "structure"
    REVIEW = "review"


class StepStatus(str, Enum):
    """Execution status of a plan step."""
    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    FAILED = "failed"
    RETRYING = "retrying"


# ─── API Models ──────────────────────────────────────────────────────────────

class AgentRequest(BaseModel):
    """Incoming request to the /agent endpoint."""
    request: str = Field(
        ...,
        min_length=5,
        max_length=5000,
        description="Natural language description of the task for the agent.",
        examples=[
            "Create a project plan for developing a mobile app for a local restaurant"
        ],
    )


# ─── Internal Agent Models ───────────────────────────────────────────────────

class PlanStep(BaseModel):
    """A single step in the agent's execution plan."""
    step_number: int = Field(..., description="Order of execution (1-based)")
    title: str = Field(..., description="Short title for this step")
    description: str = Field(..., description="What the agent will do in this step")
    step_type: StepType = Field(..., description="Category of this step")


class ExecutionPlan(BaseModel):
    """The full execution plan generated by the planner."""
    document_type: str = Field(
        ..., description="Type of document to produce (e.g., 'project_plan', 'sop', 'proposal')"
    )
    document_title: str = Field(..., description="Title for the final document")
    steps: list[PlanStep] = Field(..., description="Ordered list of steps to execute")
    reasoning: str = Field(..., description="Brief explanation of why this plan was chosen")


class StepResult(BaseModel):
    """Result of executing a single plan step."""
    step_number: int
    title: str
    status: StepStatus
    content: str = Field(default="", description="Generated content from this step")
    retries_used: int = Field(default=0, description="Number of retry attempts needed")
    error_message: Optional[str] = Field(default=None, description="Error details if step failed")


class ReflectionResult(BaseModel):
    """Result of the self-check / quality review."""
    quality_score: float = Field(
        ..., ge=1.0, le=10.0,
        description="Overall quality score from 1-10"
    )
    completeness: str = Field(..., description="Assessment of content completeness")
    coherence: str = Field(..., description="Assessment of logical flow and coherence")
    improvements: list[str] = Field(
        default_factory=list,
        description="Suggested improvements"
    )
    refined_content: Optional[str] = Field(
        default=None,
        description="Refined version of the content (if quality was below threshold)"
    )


# ─── API Response Models ────────────────────────────────────────────────────

class AgentResponse(BaseModel):
    """Full response from the /agent endpoint."""
    status: str = Field(..., description="Overall status: 'success' or 'partial_failure' or 'error'")
    request_summary: str = Field(..., description="Summary of what was requested")
    execution_plan: ExecutionPlan = Field(..., description="The plan the agent created")
    step_results: list[StepResult] = Field(..., description="Results from each step")
    reflection: Optional[ReflectionResult] = Field(
        default=None, description="Quality review results"
    )
    document_path: Optional[str] = Field(
        default=None, description="Path to the generated .docx file"
    )
    document_download_url: Optional[str] = Field(
        default=None, description="URL to download the generated document"
    )
    pdf_download_url: Optional[str] = Field(
        default=None, description="URL to download the generated PDF"
    )
    summary: str = Field(..., description="Human-readable summary of what the agent did")


class ErrorResponse(BaseModel):
    """Error response model."""
    status: str = "error"
    message: str
    details: Optional[str] = None
